def glyphs():
    """Draw original pen paths directly onto the target grid, with a slight fixed lean."""
    result={' ':Image.new('1',(4,17))}
    for ch,recipe in (UP|LOW|OTHER).items():
        strokes=[[(int(p.split(',')[0]),int(p.split(',')[1])) for p in s.split()] for s in recipe.split(';')]
        width=max(x for s in strokes for x,y in s)+3
        im=Image.new('1',(width,17));d=ImageDraw.Draw(im)
        for stroke in strokes:
            points=[(x+(1 if y<7 else 0),y) for x,y in stroke]
            d.line(points,fill=1,width=1)
        result[ch]=im
    return result

